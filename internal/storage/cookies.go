package storage

import (
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"
)

type DomainCookieMeta struct {
	Domain       string    `json:"domain"`
	CookieHeader string    `json:"cookieHeader"`
	UpdatedAt    time.Time `json:"updatedAt"`
}

// GetCookiesDir returns the directory path where session cookies are stored.
func GetCookiesDir() (string, error) {
	configDir, err := os.UserConfigDir()
	if err != nil {
		configDir = os.TempDir()
	}
	dir := filepath.Join(configDir, "godm", "cookies")
	if err := os.MkdirAll(dir, 0700); err != nil {
		return "", err
	}
	return dir, nil
}

// NormalizeDomain extracts a canonical root domain (e.g. "facebook.com" from "https://www.facebook.com/reel/...").
func NormalizeDomain(raw string) string {
	raw = strings.TrimSpace(raw)
	if strings.Contains(raw, "://") {
		if parsed, err := url.Parse(raw); err == nil && parsed.Host != "" {
			raw = parsed.Host
		}
	}
	// Strip port
	if idx := strings.Index(raw, ":"); idx != -1 {
		raw = raw[:idx]
	}
	// Strip leading dot
	raw = strings.TrimPrefix(raw, ".")
	// Strip www. or m.
	raw = strings.TrimPrefix(raw, "www.")
	raw = strings.TrimPrefix(raw, "m.")
	return strings.ToLower(raw)
}

// cdnDomainParentMap maps CDN, asset, or subsidiary domains to their primary media platform domain.
var cdnDomainParentMap = map[string]string{
	"fbcdn.net":         "facebook.com",
	"facebook.net":      "facebook.com",
	"fb.com":            "facebook.com",
	"fb.watch":          "facebook.com",
	"cdninstagram.com":  "instagram.com",
	"googlevideo.com":   "youtube.com",
	"ytimg.com":         "youtube.com",
	"twimg.com":         "twitter.com",
	"tiktokcdn.com":     "tiktok.com",
	"tiktokv.com":       "tiktok.com",
	"byteoversea.com":   "tiktok.com",
	"ibytedtos.com":     "tiktok.com",
	"redditmedia.com":   "reddit.com",
	"redd.it":           "reddit.com",
}

// GenerateNetscapeFromHeader converts a raw "name=value; name2=value2" Cookie header into Netscape format.
func GenerateNetscapeFromHeader(domain string, cookieHeader string) string {
	domain = NormalizeDomain(domain)
	if domain == "" || cookieHeader == "" {
		return ""
	}
	dotDomain := domain
	if !strings.HasPrefix(dotDomain, ".") {
		dotDomain = "." + dotDomain
	}

	var sb strings.Builder
	sb.WriteString("# Netscape HTTP Cookie File\n# Generated by godm storage\n\n")
	futureExpiry := time.Now().Add(365 * 24 * time.Hour).Unix()

	pairs := strings.Split(cookieHeader, ";")
	for _, pair := range pairs {
		pair = strings.TrimSpace(pair)
		if pair == "" {
			continue
		}
		eqIdx := strings.Index(pair, "=")
		if eqIdx == -1 {
			continue
		}
		name := strings.TrimSpace(pair[:eqIdx])
		val := strings.TrimSpace(pair[eqIdx+1:])
		if name == "" {
			continue
		}
		sb.WriteString(dotDomain)
		sb.WriteString("\tTRUE\t/\tTRUE\t")
		sb.WriteString(strings.TrimSpace(string([]byte(time.Unix(futureExpiry, 0).Format("1136214245")))))
		sb.WriteString(fmt.Sprintf("%d\t%s\t%s\n", futureExpiry, name, val))
	}
	return sb.String()
}

// SaveDomainCookies persists Netscape cookies and metadata for a domain.
func SaveDomainCookies(domain string, netscapeJar string, cookieHeader string) error {
	norm := NormalizeDomain(domain)
	if norm == "" {
		return nil
	}

	dir, err := GetCookiesDir()
	if err != nil {
		return err
	}

	// 1. Synthesize Netscape jar from raw header if jar text is not provided
	if netscapeJar == "" && cookieHeader != "" {
		netscapeJar = GenerateNetscapeFromHeader(norm, cookieHeader)
	}

	// 2. Write Netscape cookie file
	txtPath := filepath.Join(dir, norm+".txt")
	if netscapeJar != "" {
		if err := os.WriteFile(txtPath, []byte(netscapeJar), 0600); err != nil {
			return err
		}
	}

	// 3. Write JSON metadata
	meta := DomainCookieMeta{
		Domain:       norm,
		CookieHeader: cookieHeader,
		UpdatedAt:    time.Now(),
	}
	metaBytes, err := json.MarshalIndent(meta, "", "  ")
	if err == nil {
		jsonPath := filepath.Join(dir, norm+".json")
		_ = os.WriteFile(jsonPath, metaBytes, 0600)
	}

	return nil
}

// GetCookieFilePath looks up a valid Netscape cookie file for a URL or domain.
// It checks the exact domain first, falls back to parent domain (e.g. "facebook.com" for "web.facebook.com"),
// and maps known CDN domains to their primary service domain (e.g. "fbcdn.net" -> "facebook.com").
func GetCookieFilePath(rawURLOrDomain string) (string, bool) {
	norm := NormalizeDomain(rawURLOrDomain)
	if norm == "" {
		return "", false
	}

	dir, err := GetCookiesDir()
	if err != nil {
		return "", false
	}

	candidateDomains := []string{norm}
	parts := strings.Split(norm, ".")
	if len(parts) > 2 {
		root := strings.Join(parts[len(parts)-2:], ".")
		candidateDomains = append(candidateDomains, root)
	}

	// Check mapped parent domains (e.g. fbcdn.net -> facebook.com)
	count := len(candidateDomains)
	for i := 0; i < count; i++ {
		cand := candidateDomains[i]
		if parent, ok := cdnDomainParentMap[cand]; ok {
			candidateDomains = append(candidateDomains, parent)
		}
	}

	for _, d := range candidateDomains {
		exact := filepath.Join(dir, d+".txt")
		if info, err := os.Stat(exact); err == nil && info.Size() > 0 {
			return exact, true
		}
	}

	return "", false
}

// GetCookieHeader returns the raw Cookie string for a domain or its parent/CDN equivalent.
func GetCookieHeader(rawURLOrDomain string) string {
	norm := NormalizeDomain(rawURLOrDomain)
	if norm == "" {
		return ""
	}

	dir, err := GetCookiesDir()
	if err != nil {
		return ""
	}

	candidateDomains := []string{norm}
	parts := strings.Split(norm, ".")
	if len(parts) > 2 {
		root := strings.Join(parts[len(parts)-2:], ".")
		candidateDomains = append(candidateDomains, root)
	}

	count := len(candidateDomains)
	for i := 0; i < count; i++ {
		cand := candidateDomains[i]
		if parent, ok := cdnDomainParentMap[cand]; ok {
			candidateDomains = append(candidateDomains, parent)
		}
	}

	for _, d := range candidateDomains {
		jsonPath := filepath.Join(dir, d+".json")
		if data, err := os.ReadFile(jsonPath); err == nil {
			var meta DomainCookieMeta
			if err := json.Unmarshal(data, &meta); err == nil && meta.CookieHeader != "" {
				return meta.CookieHeader
			}
		}
	}

	return ""
}

// HasCookiesForDomain checks if we have stored cookies for a domain.
func HasCookiesForDomain(rawURLOrDomain string) bool {
	_, found := GetCookieFilePath(rawURLOrDomain)
	return found
}

// ListSyncedDomains returns a list of all domains that have stored cookies.
func ListSyncedDomains() []string {
	dir, err := GetCookiesDir()
	if err != nil {
		return nil
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}

	domains := make([]string, 0)
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".txt") {
			domain := strings.TrimSuffix(entry.Name(), ".txt")
			domains = append(domains, domain)
		}
	}
	return domains
}

// RemoveDomainCookies deletes stored cookies for a domain.
func RemoveDomainCookies(domain string) error {
	norm := NormalizeDomain(domain)
	if norm == "" {
		return nil
	}

	dir, err := GetCookiesDir()
	if err != nil {
		return err
	}

	_ = os.Remove(filepath.Join(dir, norm+".txt"))
	_ = os.Remove(filepath.Join(dir, norm+".json"))
	return nil
}
